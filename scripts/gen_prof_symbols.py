#!/usr/bin/env python3
"""Generate mods/coke-prof/src/symbols.rs from the local decompiled analysis.

Only function start addresses and Ghidra's auto-generated names are copied.
No decompiled bodies are written. The analysis folder is gitignored; run this
after moving/refreshing `analysis/decompiled/functions`.
"""
import argparse
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "analysis", "decompiled", "functions")
OUT = os.path.join(ROOT, "mods", "coke-prof", "src", "symbols.rs")
IMAGE_BASE = 0x00400000


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("exe", help="exact executable from which the function analysis was produced")
    args = parser.parse_args()
    length = 0
    fingerprint = 0xCBF29CE484222325
    with open(args.exe, "rb") as exe:
        for block in iter(lambda: exe.read(65536), b""):
            length += len(block)
            for byte in block:
                fingerprint = ((fingerprint ^ byte) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    rows = []
    for name in sorted(os.listdir(SRC)):
        if not name.endswith(".c"):
            continue
        path = os.path.join(SRC, name)
        addr = sym = None
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            for _ in range(12):
                line = f.readline()
                if not line:
                    break
                m = re.match(r"// address: (0x[0-9a-fA-F]+)", line)
                if m:
                    addr = int(m.group(1), 16)
                m = re.match(r"// name: (\S+)", line)
                if m:
                    sym = m.group(1)
        if addr is None or sym is None:
            continue
        rva = addr - IMAGE_BASE
        if rva > 0:
            rows.append((rva, sym))
    rows.sort()
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// @generated by scripts/gen_prof_symbols.py; addresses only.\n")
        f.write("// Sorted by RVA (image base 0x00400000). No code is included.\n")
        f.write(f"pub const EXE_FINGERPRINT: Option<(u64, u64)> = Some(({length}, 0x{fingerprint:016x}));\n")
        f.write("pub static SYMBOLS: &[(u32, &str)] = &[\n")
        for rva, sym in rows:
            f.write(f'    (0x{rva:06x}, "{sym}"),\n')
        f.write("];\n")
    print(f"{len(rows)} symbols -> {OUT}")


if __name__ == "__main__":
    main()
