// Generates the opengl32 export thunks.
//
// Every export becomes a naked stdcall thunk that jumps through an entry in a
// shared pointer table. The table is filled at load time with the address of
// the matching function in the real system opengl32.dll, so argument registers
// and the caller's stack stay untouched and no signature knowledge is needed.
//
// A short list of functions is handled by Rust bodies instead of thunks; those
// names are listed in INTERCEPTED and must be implemented in src/lib.rs.

// A thunk here is a tiny naked function that forwards the call, with its
// arguments untouched, to the real DLL entry point.

use std::env;
use std::fs;
use std::path::Path;

/// `INTERCEPTED` names are implemented by Rust bodies in `src/lib.rs` instead of
/// being forwarded to the real DLL.
const INTERCEPTED: &[&str] = &[
    "glViewport",
    "glScissor",
    "glRasterPos2i",
    "glRasterPos3f",
    "glReadPixels",
    "glCopyTexImage2D",
    "glCopyTexSubImage2D",
    "glCallList",
    "glBindTexture",
    "glBegin",
    "glEnd",
    "glPushMatrix",
    "glPopMatrix",
    "glDrawArrays",
    "glDrawElements",
    "glTexImage2D",
    "glTexSubImage2D",
    "glNewList",
    "glEndList",
    "glGenLists",
    "glDeleteLists",
    "glCallLists",
    "wglCreateContext",
    "wglMakeCurrent",
    "wglDeleteContext",
    "wglGetProcAddress",
    "wglSwapBuffers",
    "wglShareLists",
    "wglGetCurrentContext",
    "wglGetCurrentDC",
];

fn main() {
    let manifest = env::var("CARGO_MANIFEST_DIR").unwrap();
    let out_dir = env::var("OUT_DIR").unwrap();
    emit_names(&manifest, &out_dir);

    let exports_path = Path::new(&manifest).join("exports.txt");
    let raw = fs::read_to_string(&exports_path)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", exports_path.display()));

    let mut names: Vec<String> = raw
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .map(str::to_owned)
        .collect();
    names.sort();
    names.dedup();

    let intercepted: Vec<&String> = names
        .iter()
        .filter(|n| INTERCEPTED.contains(&n.as_str()))
        .collect();
    let forwarded: Vec<&String> = names
        .iter()
        .filter(|n| !INTERCEPTED.contains(&n.as_str()))
        .collect();

    let mut out = String::with_capacity(256 * 1024);
    out.push_str("// @generated by build.rs - do not edit\n");
    out.push_str(&format!(
        "pub const FORWARDED_COUNT: usize = {};\n",
        forwarded.len()
    ));
    out.push_str("pub static FORWARDED_NAMES: [&str; FORWARDED_COUNT] = [\n");
    for n in &forwarded {
        out.push_str(&format!("    \"{n}\",\n"));
    }
    out.push_str("];\n\n");

    // Generate per-function statics and resolver table for init
    out.push_str("pub static mut REAL_POINTERS: [*mut usize; FORWARDED_COUNT] = [\n");
    for n in &forwarded {
        let static_name = format!("REAL_{}", n.to_uppercase());
        out.push_str(&format!("    core::ptr::addr_of_mut!({static_name}),\n"));
    }
    out.push_str("];\n\n");

    for n in &forwarded {
        let static_name = format!("REAL_{}", n.to_uppercase());
        out.push_str(&format!("static mut {static_name}: usize = 0;\n"));
        out.push_str("#[unsafe(naked)]\n#[unsafe(no_mangle)]\n");
        out.push_str(&format!("pub extern \"system\" fn {n}() -> ! {{\n"));
        out.push_str(&format!(
            "    core::arch::naked_asm!(\"jmp dword ptr [{{s}}]\", s = sym {static_name});\n"
        ));
        out.push_str("}\n\n");
    }

    let out_dir = env::var("OUT_DIR").unwrap();
    fs::write(Path::new(&out_dir).join("thunks.rs"), out).unwrap();

    // Informational only: keep the normal build output clean. Set
    // CMBS_BUILD_VERBOSE=1 to print the export counts as a build warning.
    if env::var_os("CMBS_BUILD_VERBOSE").is_some() {
        println!(
            "cargo:warning=coke: {} forwarded exports, {} intercepted",
            forwarded.len(),
            intercepted.len()
        );
    }
    println!("cargo:rerun-if-changed=exports.txt");
    println!("cargo:rerun-if-changed=build.rs");
}

/// Keys `names.ini` must define. A missing key fails the build instead of
/// silently falling back to a hard-coded name.
const NAME_KEYS: &[&str] = &[
    "product_name",
    "config_file",
    "legacy_config_files",
    "log_file",
    "mod_dir",
    "consent_prefix",
    "consent_suffix",
    "profile_dir",
    "profiles_zip",
    "temp_dir",
    "real_dll",
    "proxy_dll",
];

/// Reads `names.ini` and writes the generated `names.rs` into `OUT_DIR`.
///
/// Every user-visible name in the crate comes from this file, so renaming the
/// mod or one of its files is a single edit. The same file is parsed by the
/// PowerShell scripts and the release workflow.
fn emit_names(manifest: &str, out_dir: &str) {
    let path = Path::new(manifest).join("names.ini");
    let raw =
        fs::read_to_string(&path).unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()));

    let mut values: Vec<(String, String)> = Vec::new();
    for line in raw.lines() {
        let line = line.split(['#', ';']).next().unwrap_or("").trim();
        if line.is_empty() {
            continue;
        }
        let Some((key, value)) = line.split_once('=') else {
            panic!("{}: expected `key = value`, found `{line}`", path.display());
        };
        let key = key.trim().to_ascii_lowercase();
        let value = value.trim().to_string();
        if value.is_empty() {
            panic!("{}: `{key}` has an empty value", path.display());
        }
        if !NAME_KEYS.contains(&key.as_str()) {
            panic!("{}: unknown key `{key}`", path.display());
        }
        values.push((key, value));
    }

    for key in NAME_KEYS {
        if !values.iter().any(|(k, _)| k == key) {
            panic!("{}: missing required key `{key}`", path.display());
        }
    }

    let get = |key: &str| -> &str {
        &values
            .iter()
            .find(|(k, _)| k == key)
            .unwrap_or_else(|| panic!("{}: missing `{key}`", path.display()))
            .1
    };
    let escape = |s: &str| s.replace('\\', "\\\\").replace('"', "\\\"");
    let ident = |key: &str| key.to_ascii_uppercase();

    let mut out = String::new();
    out.push_str("// @generated by build.rs from names.ini - do not edit\n");
    out.push_str("// Change the names in names.ini, not here.\n\n");
    for key in NAME_KEYS {
        if *key == "legacy_config_files" {
            continue;
        }
        out.push_str(&format!(
            "pub const {}: &str = \"{}\";\n",
            ident(key),
            escape(get(key))
        ));
    }

    let legacy: Vec<&str> = get("legacy_config_files")
        .split(',')
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .collect();
    out.push_str(&format!(
        "\npub const LEGACY_CONFIG_FILES: [&str; {}] = [\n",
        legacy.len()
    ));
    for name in &legacy {
        out.push_str(&format!("    \"{}\",\n", escape(name)));
    }
    out.push_str("];\n\n");

    out.push_str("/// Crate version, from Cargo.toml.\n");
    out.push_str("pub const VERSION: &str = env!(\"CARGO_PKG_VERSION\");\n\n");
    out.push_str("/// `<consent_prefix><stem><consent_suffix>` for one mod DLL.\n");
    out.push_str("pub fn consent_file(stem: &str) -> String {\n");
    out.push_str("    format!(\"{}{}{}\", CONSENT_PREFIX, stem, CONSENT_SUFFIX)\n");
    out.push_str("}\n");

    fs::write(Path::new(out_dir).join("names.rs"), out).unwrap();
    println!("cargo:rerun-if-changed=names.ini");
}
